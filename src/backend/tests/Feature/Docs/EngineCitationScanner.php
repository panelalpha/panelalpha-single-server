<?php

namespace Tests\Feature\Docs;

/**
 * Scans test sources for Engine stubs and decides whether each carries an inline
 * citation.
 *
 * A stub is anything that produces an Engine (or provider) response body:
 *  - `Http::response(`, `Http::sequence(` / `fakeSequence(` and every `->push*()`;
 *  - every top-level value of an `Http::fake([...])` array, mixed blocks
 *    included: an array/string, an int status, a variable and a closure are all
 *    stubs of their own;
 *  - `Http::fake($var)` with the array in a variable and a closure returning a
 *    variable are counted as one stub each.
 *
 * The `Http` facade is resolved by its imported name: a `use
 * Illuminate\Support\Facades\Http [as Alias]` import (or the FQCN) makes the
 * alias an Engine facade; a different `Http` import is not one. The detection
 * is token based, so brackets and arrows inside comments or strings cannot
 * confuse it.
 *
 * A stub is cited when the two lines above it (the pinned window) or above the
 * `Http::fake` / `fakeSequence` call it belongs to contain either a real
 * `// Engine: <path>:<line>` or a `// External: <source>` citation. An Engine
 * citation is accepted only when the path resolves to a committed Engine file
 * ({@see engine-paths.txt}, generated by `scripts/generate-engine-paths.sh`
 * from `core/app`, `core/config` and `core/database` only) whose committed line
 * count covers the cited line (and the end of a `:start-end` range);
 * `routes/api.php` is not accepted. A citation inside a string literal does not
 * count.
 *
 * Citation scope: a citation above a multi-entry
 * `Http::fake([...])` covers every entry only when all its keys are Engine
 * hosts; a non-Engine key needs its own `// External:` line. `// Engine:`
 * counts only on an Engine host (or a hostless stub). On an Engine host key,
 * `// Defensive (not an Engine shape): <reason>` counts as the stub's citation
 * and an `// Engine:` in the same window is then an error.
 *
 * Existing uncited stubs are listed in {@see EngineCitationBaseline}; the guard
 * test compares per file and per normalised stub text. The baseline is the
 * offender set of the `ea7c307` snapshot rescanned with this scanner and may
 * only shrink.
 *
 * A Defensive+Engine conflict in an entry's window is final (it is
 * never rescued by an ancestor citation); a Defensive marker needs a non-empty
 * reason and its comment block must reach the entry directly below it (it never
 * propagates from the enclosing `Http::fake`); `isEngineHost` strips the scheme
 * (`https://engine…`); and the `Http::fake(array(...))`, `array_merge([...])`,
 * `\Http` alias and `Facades\Http` shapes are counted.
 */
final class EngineCitationScanner
{
    /** The facade class an `Http::` call must resolve to. */
    private const HTTP_FACADE = 'Illuminate\\Support\\Facades\\Http';

    /**
     * @param  list<string>  $lines
     * @param  array<string, int|false>  $engine  citation path/suffix => line count (false = ambiguous)
     * @return array<string, int> normalised stub text => number of uncited stubs
     */
    public static function scanLines(array $lines, array $engine): array
    {
        $source = implode("\n", $lines);
        if (! str_starts_with(ltrim($source), '<?php')) {
            $source = '<?php '.$source;
        }

        // The aliases are parsed from the raw lines, so a fixture whose first
        // line is a `use` statement (no `<?php`) still resolves.
        $aliases = self::httpAliases(implode("\n", $lines));
        $comments = self::stripStrings($source);

        $offenders = [];
        foreach (self::stubLines($lines, $source, $aliases) as $stub) {
            if (! self::isCited($comments, $lines, $stub['line'], $stub['host'], $stub['fakeAllEngine'], $engine)) {
                $offenders[$stub['text']] = ($offenders[$stub['text']] ?? 0) + 1;
            }
        }

        return $offenders;
    }

    /**
     * Parse the committed `engine-paths.txt` entries (`path<TAB>lineCount`) into
     * every `/`-suffix of every path (so a citation may name the full path or
     * just its tail) mapped to that file's line count. An ambiguous suffix maps
     * to `false` and never satisfies a citation.
     *
     * @param  list<string>  $entries
     * @return array<string, int|false>
     */
    public static function pathIndex(array $entries): array
    {
        $index = [];
        foreach ($entries as $entry) {
            $entry = trim($entry);
            if ($entry === '') {
                continue;
            }

            $tab = strrpos($entry, "\t");
            $path = $tab === false ? $entry : substr($entry, 0, $tab);
            $count = $tab === false ? 0 : (int) substr($entry, $tab + 1);
            if ($path === '') {
                continue;
            }

            $parts = explode('/', $path);
            for ($i = 0, $size = count($parts); $i < $size; $i++) {
                $suffix = implode('/', array_slice($parts, $i));
                // A citation must name at least one directory.
                if (! str_contains($suffix, '/')) {
                    continue;
                }
                if (! array_key_exists($suffix, $index)) {
                    $index[$suffix] = $count;
                } elseif ($index[$suffix] !== false) {
                    $index[$suffix] = false;
                }
            }
        }

        return $index;
    }

    /**
     * Compare a scanned offender map with the committed baseline.
     *
     * Keyed per file **and** normalised stub text, so a file cannot trade one
     * fake for another (a new uncited stub of a different shape is `grown` even
     * when the file's total is unchanged) and line shifts do not matter.
     *
     * @param  array<string, array<string, int>>  $current
     * @param  array<string, array<string, int>>  $baseline
     * @return array{grown: list<string>, shrunk: list<string>}
     */
    public static function baselineDiff(array $current, array $baseline): array
    {
        $grown = [];
        foreach ($current as $file => $counts) {
            foreach ($counts as $text => $count) {
                $allowed = $baseline[$file][$text] ?? 0;
                if ($count > $allowed) {
                    $grown[] = "{$file} ({$count} > {$allowed}): {$text}";
                }
            }
        }

        $shrunk = [];
        foreach ($baseline as $file => $counts) {
            foreach ($counts as $text => $count) {
                $currentCount = $current[$file][$text] ?? 0;
                if ($currentCount < $count) {
                    $shrunk[] = "{$file} ({$currentCount} < {$count}): {$text}";
                }
            }
        }

        return ['grown' => $grown, 'shrunk' => $shrunk];
    }

    /**
     * Every stub the source carries, with the enclosing `Http::fake` host key
     * (when it has one) and whether every key of that fake is an Engine host,
     * so the citation scope can be applied.
     *
     * @param  list<string>  $lines
     * @return list<array{line: int, text: string, host: ?string, fakeAllEngine: bool}>
     */
    private static function stubLines(array $lines, string $source, array $aliases): array
    {
        $tokens = self::significantTokens($source);
        $lineHosts = [];
        $lineAllEngine = [];
        $stubs = [];

        // First pass: the `Http::fake` arrays and their host keys.
        $count = count($tokens);
        for ($i = 0; $i < $count; $i++) {
            if (! self::isHttpCall($tokens, $i, 'fake', $aliases)) {
                continue;
            }

            $open = $i + 3; // Http :: fake (
            $first = self::nextSignificant($tokens, $open);
            $close = self::matchingBracket($tokens, $open);
            $elements = $first === null ? null : self::fakeElements($tokens, $first, $aliases);

            if ($elements !== null) {
                $allEngine = true;
                foreach ($elements as $element) {
                    if ($element['host'] === null || ! self::isEngineHost($element['host'])) {
                        $allEngine = false;
                    }
                }

                foreach ($elements as $element) {
                    foreach ($element['lines'] as $line) {
                        if ($element['host'] !== null) {
                            $lineHosts[$line] = $element['host'];
                        }
                        $lineAllEngine[$line] = $allEngine;
                    }
                    if ($element['hasInlineStub']) {
                        continue;
                    }
                    if ($element['isClosure'] && ! $element['returnsArray'] && ! $element['returnsVariable']) {
                        continue;
                    }
                    $stubs[] = [
                        'line' => $element['line'],
                        'text' => self::normalise($element['value']),
                        'host' => $element['host'],
                        'fakeAllEngine' => $allEngine,
                    ];
                }
            } elseif ($first !== null) {
                // `Http::fake($var)` with the array in a variable, or a closure
                // returning an array/variable: one stub unless it wraps inline
                // stubs.
                if (! self::containsInlineStub($tokens, $first, $close, $aliases)
                    && self::isCountedNonArrayStub($tokens, $first, $close)
                ) {
                    $stubs[] = [
                        'line' => $tokens[$i][2] - 1,
                        'text' => self::normalise(self::tokenText($tokens, $first, $close)),
                        'host' => null,
                        'fakeAllEngine' => true,
                    ];
                }
            }

            $i = $close;
        }

        // Second pass: the inline `Http::response` / `Http::sequence` / `->push*()`
        // stubs, each attributed to its host key when it sits in a fake array.
        for ($i = 0; $i < $count; $i++) {
            if (! self::isInlineStub($tokens, $i, $aliases)) {
                continue;
            }
            $line = $tokens[$i][2] - 1;
            $stubs[] = [
                'line' => $line,
                'text' => self::normalise($lines[$line] ?? self::tokenText($tokens, $i, $i)),
                'host' => $lineHosts[$line] ?? null,
                'fakeAllEngine' => $lineAllEngine[$line] ?? true,
            ];
        }

        return $stubs;
    }

    /**
     * The bracket index of an array literal starting at $index: `[` itself, or
     * the `(` of an `array(...)`.
     *
     * @param  list<array{0: ?int, 1: string, 2: int}>  $tokens
     */
    private static function arrayOpenIndex(array $tokens, int $index): ?int
    {
        if (self::isArrayOpen($tokens[$index])) {
            return $index;
        }
        if (($tokens[$index][0] ?? null) === T_ARRAY && ($tokens[$index + 1][1] ?? null) === '(') {
            return $index + 1;
        }

        return null;
    }

    /**
     * The elements of a fake argument that is an array literal or an
     * `array_merge([...], [...])`; null when it is neither, so the caller falls
     * back to the single-stub shapes.
     *
     * @param  list<array{0: ?int, 1: string, 2: int}>  $tokens
     * @param  list<string>  $aliases
     * @return list<array{line: int, value: string, host: ?string, lines: list<int>, hasInlineStub: bool, isClosure: bool, returnsArray: bool, returnsVariable: bool}>|null
     */
    private static function fakeElements(array $tokens, int $first, array $aliases): ?array
    {
        $opens = [];
        $direct = self::arrayOpenIndex($tokens, $first);
        if ($direct !== null) {
            $opens[] = $direct;
        } elseif (($tokens[$first][0] ?? null) === T_STRING
            && $tokens[$first][1] === 'array_merge'
            && ($tokens[$first + 1][1] ?? null) === '('
        ) {
            $funcClose = self::matchingBracket($tokens, $first + 1);
            $depth = 0;
            for ($i = $first + 2; $i < $funcClose; $i++) {
                if ($depth === 0) {
                    $openIndex = self::arrayOpenIndex($tokens, $i);
                    if ($openIndex !== null) {
                        $opens[] = $openIndex;
                    }
                }
                if (self::isBracketOpen($tokens[$i][1])) {
                    $depth++;
                } elseif (self::isBracketClose($tokens[$i][1])) {
                    $depth--;
                }
            }
        } else {
            return null;
        }

        $elements = [];
        foreach ($opens as $openIndex) {
            $elements = array_merge($elements, self::arrayElements($tokens, $openIndex, $aliases));
        }

        return $elements;
    }

    /**
     * The top-level elements of the array whose opening bracket is at $open.
     *
     * @param  list<array{0: ?int, 1: string, 2: int}>  $tokens
     * @return list<array{line: int, value: string, host: ?string, lines: list<int>, hasInlineStub: bool, isClosure: bool, returnsArray: bool, returnsVariable: bool}>
     */
    private static function arrayElements(array $tokens, int $open, array $aliases): array
    {
        $elements = [];
        $close = self::matchingBracket($tokens, $open);
        $depth = 0;
        $start = $open + 1;
        $arrow = null;

        for ($i = $open + 1; $i < $close; $i++) {
            $token = $tokens[$i];
            if (self::isBracketOpen($token[1])) {
                $depth++;

                continue;
            }
            if (self::isBracketClose($token[1])) {
                $depth--;

                continue;
            }
            if ($depth === 0 && $token[1] === ',') {
                $elements[] = self::buildElement($tokens, $start, $i, $arrow, $aliases);
                $start = $i + 1;
                $arrow = null;

                continue;
            }
            if ($depth === 0 && $arrow === null && $token[0] === T_DOUBLE_ARROW) {
                $arrow = $i;
            }
        }

        if ($start < $close) {
            $elements[] = self::buildElement($tokens, $start, $close, $arrow, $aliases);
        }

        return array_values(array_filter($elements, static fn (?array $element): bool => $element !== null));
    }

    /**
     * A key written as strings joined with `.` and `TestNetwork::CONSTANT` (an address
     * a test takes from the test network), read as the text it evaluates to.
     *
     * @param  list<array{0: ?int, 1: string, 2: int}>  $tokens
     */
    private static function concatenatedHost(array $tokens, int $start, int $arrow): ?string
    {
        $host = '';
        $significant = [];
        for ($i = $start; $i < $arrow; $i++) {
            if (! in_array($tokens[$i][0], [T_WHITESPACE, T_COMMENT, T_DOC_COMMENT], true)) {
                $significant[] = $tokens[$i];
            }
        }
        for ($i = 0; $i < count($significant); $i++) {
            $token = $significant[$i];
            if ($token[0] === T_CONSTANT_ENCAPSED_STRING) {
                $host .= stripcslashes(substr($token[1], 1, -1));
            } elseif ($token[1] === '.') {
                continue;
            } elseif ($token[0] === T_STRING && $token[1] === 'TestNetwork' && ($significant[$i + 1][0] ?? null) === T_DOUBLE_COLON && ($significant[$i + 2][0] ?? null) === T_STRING) {
                $constant = \Tests\Support\TestNetwork::class.'::'.$significant[$i + 2][1];
                if (! defined($constant)) {
                    return null;
                }
                $host .= constant($constant);
                $i += 2;
            } else {
                return null;
            }
        }

        return $host === '' ? null : $host;
    }

    /**
     * @param  list<array{0: ?int, 1: string, 2: int}>  $tokens
     * @return array{line: int, value: string, host: ?string, lines: list<int>, hasInlineStub: bool, isClosure: bool, returnsArray: bool, returnsVariable: bool}|null
     */
    private static function buildElement(array $tokens, int $start, int $end, ?int $arrow, array $aliases): ?array
    {
        $start = self::nextSignificant($tokens, $start - 1);
        if ($start === null || $start > $end) {
            return null;
        }
        if ($arrow !== null && $arrow >= $end) {
            $arrow = null;
        }

        $host = null;
        if ($arrow !== null && ($start + 1) === $arrow && $tokens[$start][0] === T_CONSTANT_ENCAPSED_STRING) {
            $host = stripcslashes(substr($tokens[$start][1], 1, -1));
        } elseif ($arrow !== null) {
            $host = self::concatenatedHost($tokens, $start, $arrow);
        }

        $valueStart = $arrow !== null ? self::nextSignificant($tokens, $arrow) : $start;
        if ($valueStart === null || $valueStart > $end) {
            return null;
        }

        $lines = [];
        for ($i = $start; $i < $end; $i++) {
            $lines[$tokens[$i][2] - 1] = true;
        }

        return [
            'line' => $tokens[$start][2] - 1,
            'value' => self::tokenText($tokens, $valueStart, $end),
            'host' => $host,
            'lines' => array_map('intval', array_keys($lines)),
            'hasInlineStub' => self::containsInlineStub($tokens, $valueStart, $end, $aliases),
            'isClosure' => self::isClosureStart($tokens[$valueStart]),
            'returnsArray' => preg_match('~=>\s*\[|return\s*\[~', self::tokenText($tokens, $valueStart, $end)) === 1,
            'returnsVariable' => preg_match('~=>\s*\$|return\s*\$~', self::tokenText($tokens, $valueStart, $end)) === 1,
        ];
    }

    /**
     * `Http::fake(<expr>)` counts as one stub when the expression is a variable
     * or a closure returning an array or a variable.
     *
     * @param  list<array{0: ?int, 1: string, 2: int}>  $tokens
     */
    private static function isCountedNonArrayStub(array $tokens, int $start, int $end): bool
    {
        if (($tokens[$start][0] ?? null) === T_VARIABLE) {
            return true;
        }
        if (! self::isClosureStart($tokens[$start])) {
            return false;
        }

        return preg_match('~=>\s*\[|return\s*\[|=>\s*\$|return\s*\$~', self::tokenText($tokens, $start, $end)) === 1;
    }

    /**
     * @param  list<array{0: ?int, 1: string, 2: int}>  $tokens
     */
    private static function containsInlineStub(array $tokens, int $start, int $end, array $aliases): bool
    {
        for ($i = $start; $i <= $end && isset($tokens[$i]); $i++) {
            if (self::isInlineStub($tokens, $i, $aliases) || self::isHttpCall($tokens, $i, 'failedConnection', $aliases)) {
                return true;
            }
        }

        return false;
    }

    /**
     * @param  list<array{0: ?int, 1: string, 2: int}>  $tokens
     */
    private static function isInlineStub(array $tokens, int $i, array $aliases): bool
    {
        if (self::isHttpCall($tokens, $i, 'response', $aliases)
            || self::isHttpCall($tokens, $i, 'sequence', $aliases)
            || self::isHttpCall($tokens, $i, 'fakeSequence', $aliases)
        ) {
            return true;
        }

        return $tokens[$i][1] === '->'
            && isset($tokens[$i + 1])
            && $tokens[$i + 1][0] === T_STRING
            && str_starts_with($tokens[$i + 1][1], 'push')
            && isset($tokens[$i + 2])
            && $tokens[$i + 2][1] === '(';
    }

    /**
     * `Http::<method>(` starting at token $i, resolving the facade's imported
     * name.
     *
     * @param  list<array{0: ?int, 1: string, 2: int}>  $tokens
     * @param  list<string>  $aliases
     */
    private static function isHttpCall(array $tokens, int $i, string $method, array $aliases): bool
    {
        return self::isHttpFacade($tokens, $i, $aliases)
            && ($tokens[$i + 1][1] ?? null) === '::'
            && ($tokens[$i + 2][0] ?? null) === T_STRING
            && $tokens[$i + 2][1] === $method
            && ($tokens[$i + 3][1] ?? null) === '(';
    }

    /**
     * @param  list<array{0: ?int, 1: string, 2: int}>  $tokens
     * @param  list<string>  $aliases
     */
    private static function isHttpFacade(array $tokens, int $i, array $aliases): bool
    {
        $token = $tokens[$i] ?? null;
        if ($token === null) {
            return false;
        }

        if ($token[0] === T_STRING && in_array($token[1], $aliases, true)) {
            return true;
        }

        if (! in_array($token[0], [T_NAME_FULLY_QUALIFIED, T_NAME_QUALIFIED], true)) {
            return false;
        }

        // The FQCN, the root `\Http` alias and the `Facades\Http` suffix all
        // reach the facade.
        $name = ltrim($token[1], '\\');

        return $name === self::HTTP_FACADE
            || $name === 'Http'
            || $name === 'Facades\\Http'
            || str_ends_with($name, '\\Facades\\Http');
    }

    /**
     * The short names `Http` may be imported as.
     * `Http` stays valid by default; a different `Http` import removes it.
     *
     * @return list<string>
     */
    private static function httpAliases(string $source): array
    {
        $aliases = ['Http'];
        $imports = [];

        foreach (preg_split('/\R/', $source) ?: [] as $line) {
            if (preg_match('/^\s*use\s+([^;]+);/', $line, $matches) !== 1) {
                continue;
            }

            $import = trim($matches[1]);
            if (preg_match('/^(.+)\\\\\{(.+)\}$/', $import, $group) === 1) {
                $prefix = rtrim($group[1], '\\');
                foreach (explode(',', $group[2]) as $part) {
                    $imports[] = self::importTarget($prefix.'\\'.trim($part), $part);
                }

                continue;
            }

            $imports[] = self::importTarget($import, $import);
        }

        foreach ($imports as [$fqcn, $name]) {
            if ($fqcn === self::HTTP_FACADE) {
                $aliases[] = $name;
            } elseif ($name === 'Http' && $fqcn !== self::HTTP_FACADE) {
                // A different `Http` import shadows the facade.
                $aliases = array_values(array_diff($aliases, ['Http']));
            }
        }

        return array_values(array_unique($aliases));
    }

    /**
     * @return array{0: string, 1: string}
     */
    private static function importTarget(string $raw, string $part): array
    {
        if (preg_match('/^(.+?)\s+as\s+(\w+)$/i', trim($part), $alias) === 1) {
            return [ltrim($alias[1], '\\'), $alias[2]];
        }

        $fqcn = ltrim($raw, '\\');
        $segments = explode('\\', $fqcn);

        return [$fqcn, end($segments) ?: $fqcn];
    }

    /**
     * @param  list<array{0: ?int, 1: string, 2: int}>  $tokens
     */
    private static function isClosureStart(array $token): bool
    {
        return $token[0] === T_FN || $token[0] === T_FUNCTION;
    }

    private static function isArrayOpen(array $token): bool
    {
        return $token[1] === '[';
    }

    private static function isBracketOpen(string $text): bool
    {
        return $text === '[' || $text === '(' || $text === '{';
    }

    private static function isBracketClose(string $text): bool
    {
        return $text === ']' || $text === ')' || $text === '}';
    }

    /**
     * Index of the bracket matching the one at $open.
     *
     * @param  list<array{0: ?int, 1: string, 2: int}>  $tokens
     */
    private static function matchingBracket(array $tokens, int $open): int
    {
        $depth = 0;
        for ($i = $open, $count = count($tokens); $i < $count; $i++) {
            if (self::isBracketOpen($tokens[$i][1])) {
                $depth++;
            } elseif (self::isBracketClose($tokens[$i][1])) {
                $depth--;
                if ($depth === 0) {
                    return $i;
                }
            }
        }

        return count($tokens) - 1;
    }

    /**
     * @param  list<array{0: ?int, 1: string, 2: int}>  $tokens
     */
    private static function nextSignificant(array $tokens, int $after): ?int
    {
        for ($i = $after + 1, $count = count($tokens); $i < $count; $i++) {
            return $i;
        }

        return null;
    }

    /**
     * The significant tokens of the source (comments and whitespace dropped),
     * each with its 1-based line.
     *
     * @return list<array{0: ?int, 1: string, 2: int}>
     */
    private static function significantTokens(string $source): array
    {
        $tokens = [];
        $line = 1;
        foreach (token_get_all($source) as $token) {
            if (is_array($token)) {
                $id = $token[0];
                $text = $token[1];
                if (! in_array($id, [T_WHITESPACE, T_COMMENT, T_DOC_COMMENT], true)) {
                    $tokens[] = [$id, $text, $line];
                }
            } else {
                $tokens[] = [null, $token, $line];
            }
            $line += substr_count(is_array($token) ? $token[1] : $token, "\n");
        }

        return $tokens;
    }

    /**
     * The source with string-literal contents blanked out, line numbers
     * preserved, so a `// Engine:` inside a string is not a citation. Comments are kept.
     *
     * @return list<string>
     */
    private static function stripStrings(string $source): array
    {
        $out = '';
        foreach (token_get_all($source) as $token) {
            if (is_array($token)) {
                if (in_array($token[0], [T_CONSTANT_ENCAPSED_STRING, T_ENCAPSED_AND_WHITESPACE], true)) {
                    $out .= (string) preg_replace('/[^\n]/', ' ', $token[1]);

                    continue;
                }
                $out .= $token[1];
            } else {
                $out .= $token;
            }
        }

        return explode("\n", $out);
    }

    /**
     * @param  list<array{0: ?int, 1: string, 2: int}>  $tokens
     */
    private static function tokenText(array $tokens, int $start, int $end): string
    {
        $parts = [];
        for ($i = $start; $i <= $end && isset($tokens[$i]); $i++) {
            $parts[] = $tokens[$i][1];
        }

        return trim(implode(' ', $parts));
    }

    /**
     * @param  list<string>  $comments  source with string literals blanked out
     * @param  list<string>  $lines  the raw source lines
     * @param  array<string, int|false>  $engine
     */
    private static function isCited(array $comments, array $lines, int $index, ?string $host, bool $fakeAllEngine, array $engine): bool
    {
        $own = self::citationState($comments, $index, $host, $engine);
        if ($own !== null) {
            // True (cited) or false (a Defensive+Engine conflict):
            // a conflict is final, so an ancestor citation must not rescue it.
            return $own;
        }

        // A citation above a multi-entry `Http::fake([...])` covers
        // every entry only when all its keys are Engine hosts.
        if (! $fakeAllEngine) {
            return false;
        }

        // A multi-line `Http::fake([...])` or `fakeSequence()` chain carries its
        // citation above the call, not above every stub line.
        for ($j = $index - 1, $steps = 0; $j >= 0 && $steps < 40; $j--, $steps++) {
            $line = $lines[$j] ?? '';
            if (trim($line) === '') {
                break;
            }
            if (preg_match('~Http::fake\s*\(|\bfakeSequence\s*\(~', $comments[$j] ?? '') === 1) {
                return self::citationState($comments, $j, $host, $engine, false) === true;
            }
            // Do not climb past the end of an unrelated previous statement.
            if (preg_match('~;\s*$~', $line) === 1) {
                break;
            }
        }

        return false;
    }

    /**
     * The citation state of a stub's own window.
     *
     *  - true  = cited in this window;
     *  - false = definitively uncited (a non-Engine key with no External, or a
     *            Defensive+Engine conflict, which is final);
     *  - null  = nothing in the window, so an ancestor `Http::fake` may still
     *            cover an all-Engine multi-entry fake.
     *
     * @param  list<string>  $comments  source with string literals blanked out
     * @param  array<string, int|false>  $engine
     */
    private static function citationState(array $comments, int $index, ?string $host, array $engine, bool $allowDefensive = true): ?bool
    {
        $from = max(0, $index - 2);
        $window = array_slice($comments, $from, $index - $from);

        $engineCitation = false;
        $external = false;
        foreach ($window as $line) {
            if (preg_match('~//\s*External:\s*\S+~', $line) === 1) {
                $external = true;
            }
            if (self::isEngineCitation($line, $engine)) {
                $engineCitation = true;
            }
        }

        // A Defensive marker needs a non-empty reason and covers only the entry
        // directly below it: the comment block must reach the entry, and it
        // never propagates from the enclosing `Http::fake`.
        $defensive = $allowDefensive && self::defensiveCovers($comments, $index);

        if ($host === null || self::isEngineHost($host)) {
            if ($defensive) {
                // The conflict is final: an Engine citation in the same window
                // is an error.
                return $engineCitation ? false : true;
            }

            return $engineCitation ? true : null;
        }

        // A non-Engine key needs its own `// External:` line.
        return $external ? true : false;
    }

    /**
     * Whether a valid Defensive marker's comment block reaches this entry.
     *
     * @param  list<string>  $comments  source with string literals blanked out
     */
    private static function defensiveCovers(array $comments, int $index): bool
    {
        for ($marker = max(0, $index - 2); $marker < $index; $marker++) {
            if (preg_match('~//\s*Defensive \(not an Engine shape\):\s*\S+~', $comments[$marker] ?? '') !== 1) {
                continue;
            }
            for ($between = $marker + 1; $between < $index; $between++) {
                if (! str_starts_with(ltrim($comments[$between] ?? ''), '//')) {
                    continue 2;
                }
            }

            return true;
        }

        return false;
    }

    /**
     * @param  array<string, int|false>  $engine
     */
    private static function isEngineCitation(string $line, array $engine): bool
    {
        return preg_match('~//\s*Engine:\s*([^\s:`)]+):(\d+)(?:-(\d+))?~', $line, $matches) === 1
            && ! str_ends_with($matches[1], 'routes/api.php')
            && self::lineExists($engine, $matches[1], (int) $matches[2], isset($matches[3]) ? (int) $matches[3] : null);
    }

    /**
     * @param  array<string, int|false>  $engine
     */
    private static function lineExists(array $engine, string $path, int $start, ?int $end): bool
    {
        $count = $engine[$path] ?? null;
        if (! is_int($count)) {
            return false;
        }

        return $start >= 1 && $start <= $count && ($end === null || ($end >= $start && $end <= $count));
    }

    /**
     * Every `engine*` host is an Engine host; `*` and an empty host are both,
     * and a scheme prefix (`https://engine…`) is stripped first.
     */
    private static function isEngineHost(string $host): bool
    {
        if ($host === '*' || $host === '') {
            return true;
        }

        $host = (string) preg_replace('~^[a-z][a-z0-9+.-]*://~i', '', $host);

        return str_starts_with(strtolower($host), 'engine');
    }

    private static function normalise(string $line): string
    {
        return trim((string) preg_replace('~\s+~', ' ', $line));
    }
}
