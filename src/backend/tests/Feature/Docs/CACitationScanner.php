<?php

namespace Tests\Feature\Docs;

/**
 * Scans test sources for Client Area request/assertion stubs and decides
 * whether each carries an inline citation.
 *
 * A **request stub** is a test HTTP client call on the test case itself
 * (`$this->getJson(...)`, `$this->actingAs($u)->putJson(...)`, `$this->json(
 * 'POST', ...)`, …) – the receiver chain must resolve to `$this`, so a
 * `$response->json('data')` read is not a stub. It must carry a
 * `// CA: <path>:<line>` citation above it: the request body is copied from the
 * CA call site.
 *
 * A **reads stub** is a response-shape assertion (`assertJson`,
 * `assertExactJson`, `assertJsonStructure`, `assertJsonPath`,
 * `assertJsonFragment`, `assertJsonCount`, `assertJsonMissing`,
 * `assertJsonValidationErrors`, `assertSee`, `assertSeeText`, `assertDontSee`,
 * `assertDontSeeText`) – any receiver, because a `$response->assertJson(...)`
 * in a later statement is still a test response assertion. It must carry a
 * `// CA reads: <path>:<line>` citation above it: the keys are the ones the CA
 * actually reads.
 *
 * A citation is accepted when its path resolves to a committed Client Area file
 * ({@see client-area-paths.txt}, generated by
 * `scripts/generate-client-area-paths.sh` from `src` and `fm` only) whose
 * committed line count covers the cited line (or the end of a `:start-end`
 * range). A citation must name at least one directory, so a bare file name is
 * not accepted. A citation inside a string literal does not count, and a
 * citation is only searched for in the stub's own statement (the lines up to
 * the previous blank line or statement terminator).
 *
 * Existing uncited stubs are listed in {@see CACitationBaseline}; the guard test
 * compares per file and per normalised stub text. The baseline is the offender
 * set of the `v1/r8-a` start tree rescanned with this scanner and may
 * only shrink.
 */
final class CACitationScanner
{
    /** Test-client methods whose call is a request stub. */
    private const REQUEST_METHODS = [
        'get', 'getJson',
        'post', 'postJson',
        'put', 'putJson',
        'patch', 'patchJson',
        'delete', 'deleteJson',
        'options', 'optionsJson',
        'head', 'json', 'call',
    ];

    /** Assertion methods whose call is a reads stub. */
    private const READS_METHODS = [
        'assertJson', 'assertExactJson', 'assertJsonStructure', 'assertJsonPath',
        'assertJsonFragment', 'assertJsonCount', 'assertJsonMissing',
        'assertJsonMissingExact', 'assertJsonValidationErrors',
        'assertSee', 'assertSeeText', 'assertDontSee', 'assertDontSeeText',
    ];

    /**
     * Methods a test-client receiver chain may pass through. A chain containing
     * any other method (`$this->client()->get(...)`) is not a CA request.
     */
    private const CHAIN_METHODS = [
        'actingAs', 'withHeader', 'withHeaders', 'withUnencryptedCookie', 'withCookie',
        'withCredentials', 'withSession', 'withoutMiddleware', 'withoutExceptionHandling',
        'followingRedirects', 'from', 'flushSession', 'startSession', 'withServerVariables',
    ];

    /**
     * With $admin (the Admin Area tests, AdminAreaCitationGuardTest) a stub may
     * also be cited `// AA: <path>:<line>` / `// AA reads: <path>:<line>` against
     * the Admin Area SPA's committed paths; a `CA` citation still has to resolve
     * in the Client Area paths.
     *
     * @param  list<string>  $lines
     * @param  array<string, int|false>  $client  citation path/suffix => line count (false = ambiguous)
     * @param  array<string, int|false>|null  $admin  the Admin Area paths, when AA citations count
     * @return array<string, int> normalised stub text => number of uncited stubs
     */
    public static function scanLines(array $lines, array $client, ?array $admin = null): array
    {
        $source = implode("\n", $lines);
        if (! str_starts_with(ltrim($source), '<?php')) {
            $source = '<?php '.$source;
        }

        $comments = self::stripStrings($source);
        $tokens = self::significantTokens($source);

        $offenders = [];
        $count = count($tokens);
        for ($i = 0; $i + 2 < $count; $i++) {
            if ($tokens[$i][1] !== '->' || ($tokens[$i + 2][1] ?? null) !== '(') {
                continue;
            }
            if ($tokens[$i + 1][0] !== T_STRING) {
                continue;
            }

            $method = $tokens[$i + 1][1];
            $line = $tokens[$i][2] - 1;

            if (in_array($method, self::REQUEST_METHODS, true)) {
                if (! self::receiverIsThis($tokens, $i)) {
                    continue;
                }
                // `json()` and `call()` are also response reads (`->json('data')`):
                // only the two-plus argument form is a test-client request.
                if (in_array($method, ['json', 'call'], true)
                    && ! self::hasAtLeastArguments($tokens, $i + 2, 2)
                ) {
                    continue;
                }
                if (! self::isCited($comments, $lines, $line, '//\s*CA:\s*', $client)
                    && ($admin === null || ! self::isCited($comments, $lines, $line, '//\s*AA:\s*', $admin))
                ) {
                    $key = 'request: '.self::normalise($lines[$line] ?? $method);
                    $offenders[$key] = ($offenders[$key] ?? 0) + 1;
                }
            } elseif (in_array($method, self::READS_METHODS, true)) {
                if (! self::isCited($comments, $lines, $line, '//\s*CA\s+reads:\s*', $client)
                    && ($admin === null || ! self::isCited($comments, $lines, $line, '//\s*AA\s+reads:\s*', $admin))
                ) {
                    $key = 'reads: '.self::normalise($lines[$line] ?? $method);
                    $offenders[$key] = ($offenders[$key] ?? 0) + 1;
                }
            }
        }

        return $offenders;
    }

    /**
     * Parse the committed `client-area-paths.txt` entries (`path<TAB>lineCount`)
     * into every `/`-suffix of every path, so a citation may name the full path
     * (`packages/client-area/src/...`) or a shorter tail (`src/...`, `views/...`,
     * `fm/...`). An ambiguous suffix maps to `false` and never satisfies a
     * citation.
     *
     * @param  list<string>  $entries
     * @return array<string, int|false>
     */
    public static function pathIndex(array $entries): array
    {
        $index = [];
        foreach ($entries as $entry) {
            $entry = trim($entry);
            if ($entry === '') {
                continue;
            }

            $tab = strrpos($entry, "\t");
            $path = $tab === false ? $entry : substr($entry, 0, $tab);
            $count = $tab === false ? 0 : (int) substr($entry, $tab + 1);
            if ($path === '') {
                continue;
            }

            $parts = explode('/', $path);
            for ($i = 0, $size = count($parts); $i < $size; $i++) {
                $suffix = implode('/', array_slice($parts, $i));
                // A citation must name at least one directory.
                if (! str_contains($suffix, '/')) {
                    continue;
                }
                if (! array_key_exists($suffix, $index)) {
                    $index[$suffix] = $count;
                } elseif ($index[$suffix] !== false) {
                    $index[$suffix] = false;
                }
            }
        }

        return $index;
    }

    /**
     * Compare a scanned offender map with the committed baseline.
     *
     * Keyed per file **and** normalised stub text, so a file cannot trade one
     * stub for another (a new uncited stub of a different shape is `grown` even
     * when the file's total is unchanged) and line shifts do not matter.
     *
     * @param  array<string, array<string, int>>  $current
     * @param  array<string, array<string, int>>  $baseline
     * @return array{grown: list<string>, shrunk: list<string>}
     */
    public static function baselineDiff(array $current, array $baseline): array
    {
        $grown = [];
        foreach ($current as $file => $counts) {
            foreach ($counts as $text => $count) {
                $allowed = $baseline[$file][$text] ?? 0;
                if ($count > $allowed) {
                    $grown[] = "{$file} ({$count} > {$allowed}): {$text}";
                }
            }
        }

        $shrunk = [];
        foreach ($baseline as $file => $counts) {
            foreach ($counts as $text => $count) {
                $currentCount = $current[$file][$text] ?? 0;
                if ($currentCount < $count) {
                    $shrunk[] = "{$file} ({$currentCount} < {$count}): {$text}";
                }
            }
        }

        return ['grown' => $grown, 'shrunk' => $shrunk];
    }

    /**
     * Whether the receiver chain of `->method(` at $arrow resolves to `$this`.
     *
     * `$this->getJson(` and `$this->actingAs($u)->putJson(` do;
     * `$response->json(` and `Foo::bar(` do not.
     *
     * @param  list<array{0: ?int, 1: string, 2: int}>  $tokens
     */
    private static function receiverIsThis(array $tokens, int $arrow): bool
    {
        $j = $arrow - 1;
        for ($guard = 0; $guard < 200; $guard++) {
            if ($j < 0) {
                return false;
            }

            $text = $tokens[$j][1];
            if ($text === ')' || $text === ']' || $text === '}') {
                $j = self::matchingOpen($tokens, $j) - 1;

                continue;
            }
            if ($text === '->' || $text === '::') {
                $j--;

                continue;
            }
            if ($text === '$this') {
                return true;
            }
            if ($tokens[$j][0] === T_STRING) {
                // A method name whose argument list we already stepped over: the
                // `->` / `::` before it is consumed on the next loop turn. Only a
                // test-client chain method keeps the call on the test client.
                if (! in_array($tokens[$j][1], self::CHAIN_METHODS, true)) {
                    return false;
                }
                $j--;

                continue;
            }
            if ($tokens[$j][0] === T_VARIABLE) {
                return false;
            }

            return false;
        }

        return false;
    }

    /**
     * Whether the call whose opening bracket is at $open takes at least $count
     * top-level arguments.
     *
     * @param  list<array{0: ?int, 1: string, 2: int}>  $tokens
     */
    private static function hasAtLeastArguments(array $tokens, int $open, int $count): bool
    {
        if (($tokens[$open][1] ?? null) !== '(') {
            return false;
        }

        $close = self::matchingClose($tokens, $open);
        $depth = 0;
        $commas = 0;
        for ($i = $open + 1; $i < $close; $i++) {
            $text = $tokens[$i][1];
            if (self::isBracketOpen($text)) {
                $depth++;

                continue;
            }
            if (self::isBracketClose($text)) {
                $depth--;

                continue;
            }
            if ($depth === 0 && $text === ',') {
                $commas++;
            }
        }

        return $commas + 1 >= $count;
    }

    /**
     * @param  list<array{0: ?int, 1: string, 2: int}>  $tokens
     */
    private static function matchingClose(array $tokens, int $open): int
    {
        $depth = 0;
        for ($i = $open, $count = count($tokens); $i < $count; $i++) {
            $text = $tokens[$i][1];
            if (self::isBracketOpen($text)) {
                $depth++;
            } elseif (self::isBracketClose($text)) {
                $depth--;
                if ($depth === 0) {
                    return $i;
                }
            }
        }

        return count($tokens) - 1;
    }

    /**
     * Index of the bracket opening the one at $close.
     *
     * @param  list<array{0: ?int, 1: string, 2: int}>  $tokens
     */
    private static function matchingOpen(array $tokens, int $close): int
    {
        $depth = 0;
        for ($i = $close; $i >= 0; $i--) {
            $text = $tokens[$i][1];
            if (self::isBracketClose($text)) {
                $depth++;
            } elseif (self::isBracketOpen($text)) {
                $depth--;
                if ($depth === 0) {
                    return $i;
                }
            }
        }

        return 0;
    }

    private static function isBracketOpen(string $text): bool
    {
        return $text === '[' || $text === '(' || $text === '{';
    }

    private static function isBracketClose(string $text): bool
    {
        return $text === ']' || $text === ')' || $text === '}';
    }

    /**
     * Whether a citation matching $prefix sits in the stub's own statement: the
     * two lines directly above it, then upward to the previous blank line or
     * statement terminator.
     *
     * @param  list<string>  $comments  source with string literals blanked out
     * @param  list<string>  $lines  the raw source lines
     * @param  array<string, int|false>  $client
     */
    private static function isCited(array $comments, array $lines, int $index, string $prefix, array $client): bool
    {
        for ($j = $index; $j >= 0 && $j > $index - 60; $j--) {
            $raw = $lines[$j] ?? '';
            if ($j < $index) {
                $trimmed = ltrim($raw);
                if ($trimmed === '') {
                    break;
                }
                // A comment is never a statement terminator: a citation line may
                // itself end with `;`.
                $comment = str_starts_with($trimmed, '//')
                    || str_starts_with($trimmed, '/*')
                    || str_starts_with($trimmed, '*');
                if (! $comment && preg_match('~[;{}]\s*$~', $raw) === 1) {
                    break;
                }
            }
            if (preg_match('~'.$prefix.'([^\s:`)]+):(\d+)(?:-(\d+))?~', $comments[$j] ?? '', $matches) === 1
                && self::lineExists($client, $matches[1], (int) $matches[2], isset($matches[3]) ? (int) $matches[3] : null)
            ) {
                return true;
            }
        }

        return false;
    }

    /**
     * @param  array<string, int|false>  $client
     */
    private static function lineExists(array $client, string $path, int $start, ?int $end): bool
    {
        $count = $client[$path] ?? null;
        if (! is_int($count)) {
            return false;
        }

        return $start >= 1 && $start <= $count && ($end === null || ($end >= $start && $end <= $count));
    }

    /**
     * The significant tokens of the source (comments and whitespace dropped),
     * each with its 1-based line.
     *
     * @return list<array{0: ?int, 1: string, 2: int}>
     */
    private static function significantTokens(string $source): array
    {
        $tokens = [];
        $line = 1;
        foreach (token_get_all($source) as $token) {
            if (is_array($token)) {
                $id = $token[0];
                $text = $token[1];
                if (! in_array($id, [T_WHITESPACE, T_COMMENT, T_DOC_COMMENT], true)) {
                    $tokens[] = [$id, $text, $line];
                }
            } else {
                $tokens[] = [null, $token, $line];
            }
            $line += substr_count(is_array($token) ? $token[1] : $token, "\n");
        }

        return $tokens;
    }

    /**
     * The source with string-literal contents blanked out, line numbers
     * preserved, so a `// CA:` inside a string is not a citation.
     *
     * @return list<string>
     */
    private static function stripStrings(string $source): array
    {
        $out = '';
        foreach (token_get_all($source) as $token) {
            if (is_array($token)) {
                if (in_array($token[0], [T_CONSTANT_ENCAPSED_STRING, T_ENCAPSED_AND_WHITESPACE], true)) {
                    $out .= (string) preg_replace('/[^\n]/', ' ', $token[1]);

                    continue;
                }
                $out .= $token[1];
            } else {
                $out .= $token;
            }
        }

        return explode("\n", $out);
    }

    private static function normalise(string $line): string
    {
        return trim((string) preg_replace('~\s+~', ' ', $line));
    }
}
